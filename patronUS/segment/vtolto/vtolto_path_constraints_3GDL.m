function [c, ceq, dbg] = vtolto_path_constraints_3GDL(Z, models, params, bounds)
% Path constraints of the VTOL take-off, imposed at every collocation node.
% Same propulsive limits as cruise_constraints_3GDL, plus the inflow angle
% range covered by the propeller models.

F = vtolto_forces_3GDL(Z, models, params);

% Inequalities (c <= 0)

c = [-F.CT1;...
     -F.CT2;...
     -F.CP1;...
     -F.CP2;...
     F.T1 - params.prop.T_max_eng*params.prop.num_engines;...
     F.T2 - params.prop.T_max_eng*params.prop.num_engines;...
     F.P1 - params.prop.P_max_eng*params.prop.num_engines;...
     F.P2 - params.prop.P_max_eng*params.prop.num_engines;...
     F.J1 - 1.2;...
     F.J2 - 1.2;...
     F.phi1 - pi/2;...
    -F.phi1 - pi/2;...
     F.phi2 - pi/2;...
    -F.phi2 - pi/2];

% Equalities (ceq == 0)

ceq = [];

dbg = struct();

end
