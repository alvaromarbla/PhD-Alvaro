function [c, ceq, dbg] = vtolto_path_constraints_3GDL(Z, models, params, bounds)
% Path constraints of the VTOL take-off, imposed at every collocation node.
% Same propulsive limits as cruise_constraints_3GDL, plus the inflow angle
% range covered by the propeller models. Each row is normalised by its
% limit (e.g. T/T_max - 1 <= 0) so that the multipliers of all rows are in
% comparable units; dbg.c_names labels the rows (report_constraint_activity).

F = vtolto_forces_3GDL(Z, models, params);

T_max = params.prop.T_max_eng*params.prop.num_engines;
P_max = params.prop.P_max_eng*params.prop.num_engines;
J_max = 1.2;

% Inequalities (c <= 0)

c = [-F.CT1;...
     -F.CT2;...
     -F.CP1;...
     -F.CP2;...
     F.T1/T_max - 1;...
     F.T2/T_max - 1;...
     F.P1/P_max - 1;...
     F.P2/P_max - 1;...
     F.J1/J_max - 1;...
     F.J2/J_max - 1;...
     F.phi1/(pi/2) - 1;...
    -F.phi1/(pi/2) - 1;...
     F.phi2/(pi/2) - 1;...
    -F.phi2/(pi/2) - 1];

% Equalities (ceq == 0)

ceq = [];

dbg = struct();
dbg.c_names = {'CT1 >= 0', 'CT2 >= 0', 'CP1 >= 0', 'CP2 >= 0', ...
               'T1 <= T_max', 'T2 <= T_max', 'P1 <= P_max', 'P2 <= P_max', ...
               'J1 <= 1.2', 'J2 <= 1.2', ...
               'phi1 <= 90 deg', 'phi1 >= -90 deg', 'phi2 <= 90 deg', 'phi2 >= -90 deg'};

end
